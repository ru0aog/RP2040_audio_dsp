#!/usr/bin/env python3  
# tools/bin2h.py — image.gif -> image_gif.h (rodata-массив для прошивки)  
#  
# Положите image.gif рядом со скриптом и запустите:  
#   python bin2h.py  
# Результат: image_gif.h в той же директории —  
#   static const uint8_t image_gif[] + static const uint32_t image_gif_len  

  
import os  
  
HERE = os.path.dirname(os.path.abspath(__file__))  
SRC  = os.path.join(HERE, 'image.gif')  
DST  = os.path.join(HERE, 'image_gif.h')  
NAME = 'image_gif'  
  
def main():  
    data = open(SRC, 'rb').read()  
  
    with open(DST, 'w') as f:  
        f.write('#pragma once\n')  
        f.write('#include <stdint.h>\n\n')  
        f.write('// image.gif -> %s (%d bytes), generated by bin2h.py\n\n'  
                % (NAME, len(data)))  
        f.write('static const uint8_t %s[] = {\n' % NAME)  
        for i in range(0, len(data), 12):  
            chunk = data[i:i + 12]  
            f.write('    ' + ', '.join('0x%02x' % b for b in chunk))  
            if i + 12 < len(data):  
                f.write(',')  
            f.write('\n')  
        f.write('};\n\n')  
        f.write('static const uint32_t %s_len = %d;\n' % (NAME, len(data)))  
  
    print('%s -> %s: %d bytes' % (SRC, DST, len(data)))  
  
if __name__ == '__main__':  
    main()  