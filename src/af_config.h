// ---------------------------------------------------------------------------  
// АРУ + лимитер (порт agc_limit из rx_audio.cpp)  
// ---------------------------------------------------------------------------  
#define AGC_AVG_ATT_Q24         40000       // атака медленного контура  
#define AGC_AVG_DEC_Q24         40000       // спад медленного контура  
