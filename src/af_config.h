#define AF_TX_ENV_DEC_Q24       1800u 

// Program-dependent release (этап 3): спад огибающей компрессора    
// зависит от уровня. env > порога (громкая фраза) -> быстрый release,    
// шум паузы не «подтягивается»; env <= порога -> медленный, без    
// «дыхания» на тихой речи. Порог = txgate (единая точка «тишины»).    
#define AF_TX_ENV_DEC_FAST_Q24  8000u   // быстрый спад ~35 мс @15.464 ksps    

// TX-АРУ с шумовым гейтом (перед компрессором)  
#define AF_TX_AGC_TARGET        AGC_REF   // целевой уровень = как у RX-АРУ  
#define AF_TX_AGC_MAX_X10       200u      // макс. усиление 20x (x10)  
#define AF_TX_AGC_ATT_Q24       55000u    // атака EMA огибающей ~20 мс  
#define AF_TX_AGC_REL_Q24       1800u     // спад ~600 мс  
#define AF_TX_GATE_THR          250u      // порог гейта (~-42 дБ от FS, 0 = off)  
