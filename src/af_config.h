#define AF_TX_GATE_FLOOR_Q16    4120    // нижняя ступень гейта (-24 дБ)

// Узкие режекторные нотчи в TX-тракте — вырезают тоны-наводки  
// (1 и 2 кГц). Биквад-нотч, r~0.995 -> полоса ~±20 Гц на -3 дБ.  
#define AF_TX_NOTCH1_HZ         1000u   // частота 1-го нотча  
#define AF_TX_NOTCH2_HZ         2000u   // частота 2-го нотча  
