// ---------------------------------------------------------------------------  
// Автонотч NT — NLMS-предиктор (порт notch_lms_push из rx_dsp.cpp)  
// NOTCH_N=24 и NOTCH_DELAY=96 — значения 1:1 из приёмника (там NT  
// работал на 15.625 ksps без дропов).  
