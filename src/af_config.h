#define AF_CW_BW_MAX            500  
#define AF_CW_F0_MIN            300  
#define AF_CW_F0_MAX            3000  
  
// АРУ для CW: только медленный левелинг, без быстрого лимитера.  
// При bw 80 Гц огибающая тона ~12 мс — gain должен быть практически  
// заморожен, иначе громкость прыгает рывками. Константы в ~10 раз  
// медленнее речевых: установился за ~2-3 с и держит.  
// ВНИМАНИЕ: тракт на 15.625 ksps — все постоянные времени АРУ/NT/NR  
// в отсчётах стали вдвое длиннее в секундах (та же константа = вдвое  
// медленнее реакция). Для CW-профиля это в плюс.  
#define AGC_REF               18000       // Целевой средний уровень выхода (из int16-шкалы ±32768). 
                                          // АРУ крутит усиление так, чтобы средний уровень сигнала 
                                          // стремился к ~18000 ≈ −5.2 dBFS
                                          // Больше → громче, но ближе к клиппингу  
#define AGC_MAX_GAIN          100.0f      // потолок +40 дБ: слабые сигналы  
                                          // слышны, тишина не превращается в шип
#define AGC_MIN_GAIN          0.25f       // Нижний предел: ×0.25 ≈ −12 дБ. 
                                          // Сильный сигнал ослабляется максимум в 4 раза:
                                          // защита от перегрузки и от «провала» громкости
#define CW_AGC_REF            12000       // Целевой средний уровень выхода
#define CW_AGC_ATT_Q24        100         // attack ~10x медленнее речевого  
#define CW_AGC_REL_Q24        10          // release ~10x медленнее  
