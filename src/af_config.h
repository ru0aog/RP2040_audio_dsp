// ---------------------------------------------------------------------------  
// Dynamic Presence EQ (этап 2): SNR-адаптивный подъём 2–2.7 кГц.  
// Peaking-биквад после компрессора (до клиппера), k_dyn управляется  
// огибающей ВЧ до гейта (env_hi_pre) с SNR-гейтингом — шум пауз  
// не поднимается. Все коэффициенты от AF_FS_OUT_HZ = 15464.  
// ---------------------------------------------------------------------------  
  
// Отвод env_hi_pre: HP ~1.5 кГц (биквад) + EMA после АРУ, до гейта.  
// HP отсекает гласные/F1 — огибающая реагирует в основном на согласные.  
#define AF_TX_PRES_HP_HZ        1500u   // срез HP-детектора  
// EMA огибающей детектора, Q24: атака ~3 мс, спад ~50 мс @15.464 ksps  
#define AF_TX_PRES_ENV_ATT_Q24  300000u  
#define AF_TX_PRES_ENV_REL_Q24  30000u  
  
// SNR-оценщик: трекер минимума env_hi_pre.  
// Вниз — быстро (следует за падением шума), вверх — медленно  
// (шум не «догоняет» речь). Обновление только при закрытом гейте  
// (agc_env < txgate) — речь не попадает в оценку шума.  
// Реализация в коде — сдвиговая EMA: nf += (env - nf) >> SHIFT при росте.  
#define AF_TX_PRES_NF_UP_SHIFT  12      // вверх ~медленно (EMA 1/4096)  
