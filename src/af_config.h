// ---------------------------------------------------------------------------
// Захват: ADC + DMA
// ---------------------------------------------------------------------------
#define AF_ADC_PIN              26          // GP26 = ADC0, вход НЧ-сигнала  
#define AF_TX_ADC_PIN           27          // GP27 = ADC1, вход микрофона TX    
#define AF_TX_PWM_PIN           1           // GP1 — выход TX (модуляция), через RC    
#define AF_RX_ADC_CH            0           // канал ADC для RX (GP26 = ADC0)  
#define AF_TX_ADC_CH            1           // канал ADC для TX (GP27 = ADC1)  
// Фактическая частота: adc_set_clkdiv(DIV) задаёт период DIV+1 тактов    
// clk_adc. При clk_adc=48 МГц и DIV=96 период = 97 тактов → 494845 Гц.    
// Ровно 500 кс/с недостижимо: преобразование занимает 96 тактов,    
// DIV=95 даёт пропуск каждого второго триггера (половинная частота).    
#define AF_FS_ADC_HZ            494845u     // 48000000 / 97  
#define AF_BLOCK_SAMPLES        2048u       // период 4.096 мс — slack ~400 мкс/блок
#define AF_NUM_BUFFERS          8           // рабочих буферов в SPSC-очереди (+1 scratch)

// ---------------------------------------------------------------------------
// Децимация: 494.8k -> CIC/4 -> HB/2 -> HB/2 -> HB/2 -> 15.464 ksps  
// Третий HB-каскад — как в приёмнике: весь НЧ-тракт (FIR/CW/NT/NR/AGC)
// работает на 15.625 ksps — вдвое дешевле, чем на 31.25 ksps
// ---------------------------------------------------------------------------
#define AF_CIC_R                4           // децимация CIC
#define AF_CIC_N                3           // каскадов интеграторов/гребёнок
#define AF_HB_STAGES            3           // half-band каскады
#define AF_FS_OUT_HZ            15464u      // Fs после децимации (494845 / 32)  

// ---------------------------------------------------------------------------  
// Полосовой FIR (sinc + окно Блэкмана-Харриса, Q15, симметричный)  
// На 15.625 ksps 127 отводов дают переходную полосу ~135 Гц.  
// ---------------------------------------------------------------------------  
#define AF_FIR_N                127  
#define AF_FIR_LO_HZ_DEFAULT    100         // нижний срез по умолчанию  
#define AF_FIR_HI_HZ_DEFAULT    3100        // верхний срез по умолчанию  
  
// ---------------------------------------------------------------------------  
// Телеграфный (CW) фильтр: каскад биквадов BPF после FIR  
// ---------------------------------------------------------------------------  
