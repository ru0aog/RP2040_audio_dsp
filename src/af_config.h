#define AF_TX_GATE_REL_Q24      4000u     // закрытие ~250 мс  

// All-pass симметризатор огибающей (phase rotator): выравнивает  
// пик-фактор речи -> клиппер работает эффективнее.  
// Коэффициент Q15: y = a*(x - y1) + x1; a~0.5 -> фазовый сдвиг ~90° на ~1 кГц.  
#define AF_TX_AP_COEFF_Q15      16384   // a = 0.5  
#define AF_TX_AP_ON_DEFAULT     1       // 1 = включён  
  
// Кубический клиппер вместо жёсткого: y = x - x^3/(3*FS^2), |x|<=FS.  
// Меньше гармоник на входе пост-FIR -> чище эфир.  
#define AF_TX_SOFTCLIP_ON_DEFAULT 1     // 1 = кубический, 0 = жёсткий  

// 2-полосная компрессия: кроссовер ~900 Гц (комплементарный split:  
// НЧ = IIR-ФНЧ 1-го порядка, ВЧ = x - НЧ — фазово согласованы).  
// НЧ (гласные) и ВЧ (согласные = разборчивость) сжимаются раздельно —  
// гласные не «качают» согласные.  
#define AF_TX_SPLIT_HZ          900u  
// Коэффициент ФНЧ Q15: k = 2*pi*900/15464 ~ 0.366 -> ~12000  
#define AF_TX_SPLIT_K_Q15       12000  
#define AF_TX_2BAND_ON_DEFAULT  1       // 1 = 2-полосная компрессия  
// Пороги компрессоров по полосам (ВЧ ниже — согласные слабее по природе)  
#define AF_TX_COMP_THR_LO       8192  
#define AF_TX_COMP_THR_HI       6144

// Кроссовер Butterworth 2-band (этап 4, ветка 5a): биквады LP+HP  
// Q=0.7071 на AF_TX_SPLIT_HZ, HP инвертирован -> сумма all-pass,  
// -3 дБ каждой ветви на кроссовере. Не LR2 (для LR2 нужен Q=0.5),  
// но суммарная АЧХ плоская — проверено спектром.  
// Раздельный клиппинг полос до суммирования: НЧ-пики гласных    
// не модулируют согласные.    
#define AF_TX_LR2_ON_DEFAULT    1       // 1 = LR2, 0 = старый split

// HF ducking (этап 5): ослабление НЧ-полосы при доминировании ВЧ.    
// k_duck = clamp((env_hi - env_lo/2) / (env_lo + eps), 0..1) —    
// растёт, когда согласные сильнее гласных; НЧ умножается на    
// (1 - k_duck*duck_max). Гласные не маскируют согласные.    
// Только при tx2band on. Расчёт per-block, применение per-sample.    
#define AF_TX_DUCK_ON_DEFAULT   1       // 1 = включён при старте    
#define AF_TX_DUCK_MAX_Q15      9830    // потолок ослабления 0.3 (~-3 дБ)    
// Сглаживание k_duck EMA, Q24: атака ~5 мс, спад ~80 мс @15.464 ksps    
#define AF_TX_DUCK_ATT_Q24      150000u    
#define AF_TX_DUCK_REL_Q24      20000u 

// ВЧ-эксайтер (этап 6): динамический усилитель ВЧ-полосы.  
// y += env(|hi|) * hi * mix — произведение ВЧ-полосы на её медленную  
// огибающую. НЕ гармонический эксайтер: для установившегося сигнала  
// огибающая постоянна -> новых гармоник не создаётся, меняется только  
// динамическое усиление ВЧ (AM на переходах). Субъективно — звонкие  
// согласные чётче (подтверждено A/B). Настоящая нелинейность  
// (hi*|hi|) отложена — см. BUGS.MD.  
// Работает от env_hi компрессора: в паузах подмес ~0.  
#define AF_TX_EXC_ON_DEFAULT    1    // эффект подтверждён: звонкие чётче  
#define AF_TX_EXC_MIX_Q15       3277    // подмес 0.1 (~-20 дБ)    
// ФНЧ огибающей эксайтера ~500 Гц (EMA Q24, ~10 мс @15.464 ksps)    
#define AF_TX_EXC_ENV_Q24       100000u    
// Потолок подмеса (защита от «металла»): 0.5 (~-6 дБ).  
// Должен совпадать с клампом в af_tx_set_excmix (16384).  
#define AF_TX_EXC_MIX_MAX_Q15   16384  

// k_intelligibility (этап 7): автобаланс НЧ/ВЧ-полос по env_hi/env_lo.  
// Из аудита: норма отношения ~0.4-0.53. Когда ВЧ мало (ratio < цели) —  
// hi-полоса поднимается до +boost_max; когда много — приглушается до  
// -cut_max. Цель — держать долю согласных в диапазоне разборчивости.  
// Расчёт per-block (деление раз в 64 отсчёта), применение per-sample.  
// Только при tx2band on.  
#define AF_TX_INTEL_ON_DEFAULT   1  
// Целевое отношение env_hi/env_lo, Q15: 0.47 -> ~15400  
#define AF_TX_INTEL_TGT_Q15      15400  
// Потолки коррекции, Q15: boost +6 дБ (x2), cut -6 дБ (x0.5)  
#define AF_TX_INTEL_BOOST_Q15    32768   // g_hi <= 1 + 1.0 = 2.0  
#define AF_TX_INTEL_CUT_Q15      16384   // g_hi >= 1 - 0.5 = 0.5  
// Сглаживание g_hi EMA, Q24: ~30 мс — медленнее duck, без «плавания»  
#define AF_TX_INTEL_SMOOTH_Q24   30000u  

// High-shelf полка (вариант A): статический подъём ВЧ выше ~1.8 кГц.  
// Компенсирует «Hi-Fi» плоскость тракта: для разборчивости SSB-речи  
// нужен подъём +3..+6 дБ на согласных. RBJ high-shelf биквад,  
// коэффициенты пересчитываются в af_tx_set_shelf (не в горячем пути).  
// 0 = полка off (прозрачный байпас).  
#define AF_TX_SHELF_FREQ_HZ     1800u   // частота полки  
#define AF_TX_SHELF_DB_X10_DEFAULT 0    // off: статический наклон заменён динамическим presence    
#define AF_TX_SHELF_Q_X100      71u     // Q = 0.71 (плавный склон)    
#define AF_TX_SHELF_DB_X10_MAX  60u     // потолок +6 дБ — защита от «металла»    

#define AF_TX_PRES_MAX_DB_X10   15    // потолок presence-подъёма, дБx10    
#define AF_TX_DUCK_MAX_DB_X10   30    // потолок ducking, дБx10 (-3 дБ)    

// Гейт: нижняя ступень усиления (floor) вместо полного нуля.  
