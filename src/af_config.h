// Управление по GPIO (замыкание на GND = функция включена)  
// ---------------------------------------------------------------------------  
// Селектор банка настроек: 3 бита, двоичный код (LOW=1).  
// Код 000 = ручной режим (консоль), коды 001..111 = ячейки 1..7.  
#define AF_PIN_BANK0            2           // GP2 — младший бит  
#define AF_PIN_BANK1            3           // GP3  
#define AF_PIN_BANK2            4           // GP4 — старший бит  
  
// Выключатели фильтров: LOW = фильтр включён.  
#define AF_PIN_NR               5           // GP5 — LOW -> NR on  
#define AF_PIN_NT               6           // GP6 — LOW -> NT on  
#define AF_PIN_BYPASS           7           // GP7 — LOW -> bypass (выход = вход)
#define AF_PIN_PTT              8           // GP8 — LOW -> TX (передача), open -> RX    
#define AF_PIN_REC              9           // GP9 — LOW -> запись в слот    
#define AF_PIN_PLAY             10          // GP10 — LOW -> воспроизведение слота    
  
#define AF_BANK_COUNT           7           // ячеек настроек во flash    
  
// ---------------------------------------------------------------------------    
// ---------------------------------------------------------------------------      
// Цифровой магнитофон: 7 слотов во flash, по одному на банк.      
// Запись ~7 с в RAM-буфер (56000 отсчётов @ ~7732 Гц после децимации /2),      
// сброс во flash на стопе через flash-окно af_store.      
// Слот i (банк i+1): AF_REC_FLASH_OFF + i*AF_REC_SLOT_LEN,      
// регион 0x140000..0x1EFFFF (7 × 128 КБ = 896 КБ, 224 сектора).      
// Банки занимают последний сектор 0x1FF000 — не пересекаются.      
// Запас под рост прошивки до 0x140000: ~128 КБ (сейчас занято ~1.12 МБ).      
// ---------------------------------------------------------------------------      
#define AF_REC_FLASH_OFF        0x11E000u   // слоты 0x11E000..0x1FDFFF, зазор 4 KB до banks  
#define AF_REC_SLOT_LEN         0x20000u    // 128 КБ = 32 сектора на слот      
#define AF_REC_SLOT_SEC         32u         // секторов на слот  
#define AF_REC_SLOT_SIZE        (AF_REC_SLOT_SEC * FLASH_SECTOR_SIZE)  // 128 КБ  
#define AF_REC_SLOT_COUNT       AF_BANK_COUNT   // 7 слотов = 7 банков      
#define AF_REC_FLASH_LEN        (AF_REC_SLOT_LEN * AF_REC_SLOT_COUNT)  // 0xE0000    
#define AF_REC_SEC_COUNT        (AF_REC_FLASH_LEN / FLASH_SECTOR_SIZE) // 224    
  
// RAM-буфер записи: 56000 отсчётов int16 = 112 КБ, ~7.24 с @ 7732 Гц.      
// Помещается в слот 128 КБ с запасом (заголовок/выравнивание).      
#define AF_REC_RAM_SAMP         56000u       

// Тестовый сектор ftest: последний сектор свободной зоны между    
// прошивкой (~0x0f1000) и rec-slot (0x100000).    
// НЕ пересекается ни с банками (0x1FF000), ни с rec-slot (0x100000).    
#define AF_TEST_FLASH_OFF       0x0FF000u    

